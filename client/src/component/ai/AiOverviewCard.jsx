import React, { useEffect, useState } from "react";
import { Sparkles, CheckCircle2, AlertTriangle } from "lucide-react";
import AiService from "../../service/AiService";
import "../../style/aiProduct.css";

/**
 * F2: AI overview of a product. Renders nothing if the product has too little information
 * or the AI service is unavailable: the rest of the page never depends on it.
 */
const AiOverviewCard = ({ productId, onSuggestedQuestions }) => {
    const [state, setState] = useState({ status: "loading", overview: null });

    useEffect(() => {
        let active = true;
        setState({ status: "loading", overview: null });
        AiService.getOverview(productId)
            .then((data) => {
                if (!active) return;
                if (data.status === "ready" && data.overview) {
                    setState({ status: "ready", overview: data.overview });
                    onSuggestedQuestions?.(data.overview.suggested_questions || []);
                } else {
                    setState({ status: "empty", overview: null });
                }
            })
            .catch(() => active && setState({ status: "error", overview: null }));
        return () => {
            active = false;
        };
        // onSuggestedQuestions is a setter from the parent; refetch only when the product changes
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [productId]);

    if (state.status === "loading") {
        return (
            <section className="ai-card ai-card--loading" aria-busy="true" aria-label="Loading AI overview">
                <div className="ai-card-head">
                    <Sparkles size={18} className="ai-spark" />
                    <span className="ai-card-title">AI overview</span>
                </div>
                <div className="ai-skeleton-line" />
                <div className="ai-skeleton-line ai-skeleton-line--short" />
            </section>
        );
    }
    if (state.status !== "ready") return null;

    const { summary, best_for: bestFor = [], highlights = [], watch_outs: watchOuts = [] } = state.overview;

    return (
        <section className="ai-card" aria-label="AI overview">
            <div className="ai-card-head">
                <Sparkles size={18} className="ai-spark" />
                <span className="ai-card-title">AI overview</span>
                <span className="ai-badge">Generated by AI from the product information</span>
            </div>

            <p className="ai-summary">{summary}</p>

            {bestFor.length > 0 && (
                <div className="ai-chip-row">
                    <span className="ai-chip-label">Best for</span>
                    {bestFor.map((item) => (
                        <span className="ai-chip" key={item}>{item}</span>
                    ))}
                </div>
            )}

            {highlights.length > 0 && (
                <ul className="ai-highlights">
                    {highlights.map((h) => (
                        <li key={h.title}>
                            <CheckCircle2 size={16} className="ai-icon-ok" />
                            <span><strong>{h.title}.</strong> {h.text}</span>
                        </li>
                    ))}
                </ul>
            )}

            {watchOuts.length > 0 && (
                <ul className="ai-watchouts">
                    {watchOuts.map((w) => (
                        <li key={w}>
                            <AlertTriangle size={15} className="ai-icon-low" />
                            <span>{w}</span>
                        </li>
                    ))}
                </ul>
            )}
        </section>
    );
};

export default AiOverviewCard;
